"""Velox modular environment kit (ADR 0006 sections 2, 5, 8; task 14).

Generates the concrete-and-steel bunker kit: 17 flat-shaded low-poly pieces on the 400 cm module, 5 procedural
tileable textures and a manifest the Unreal import scripts read. Everything is modelled in centimetres
(1 Blender unit = 1 cm, scene unit scale 0.01), Z up, in Unreal axes (the Y mirror of the FBX path is undone in make_object).

  blender -b --factory-startup --python Tools/blender/kit.py -- \
      --out ArtSource/Export --tex ArtSource/Textures --blend ArtSource/Kit/kit.blend

Pivot convention (docs/art/kit-spec.md): the piece's minimum X / minimum Y corner at the floor level the piece
stands on (local origin). Exceptions are listed in the PIECES table (Floor: top at Z 0; Ceiling: underside at Z 0).
Local +Y is the room side of wall pieces. UV0 is a world-space planar projection, 1 UV unit = TEX_CM cm, so the
texel density is identical on every piece. UV1 (lightmap) is generated by Unreal at import.
Deterministic: fixed seeds, no timestamps in the outputs.
"""
