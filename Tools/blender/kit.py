def check_palette():
    for name, (_tex, rgb, _r, _e) in MATERIALS.items():
        if name in PALETTE_EXEMPT:
            continue
        v = max(rgb)
        s = 0.0 if v == 0 else (v - min(rgb)) / v
        assert v <= 0.5 + 1e-6 and s <= 0.25 + 1e-6, f"palette violation {name}: V={v:.2f} S={s:.2f}"


# ---------------------------------------------------------------- geometry builder
class Builder:
    def __init__(self):
        self.verts = []
        self._index = {}
        self.faces = []  # vertex index tuples (tri or quad)

    def _v(self, p):
        key = (round(float(p[0]), 4), round(float(p[1]), 4), round(float(p[2]), 4))
        if key not in self._index:
            self._index[key] = len(self.verts)
            self.verts.append(key)
        return self._index[key]

    def face(self, pts, outward):
        """Add a planar tri/quad, winding flipped so its normal points along `outward`."""
        assert len(pts) in (3, 4)
        a, b, c = (np.array(pts[i], float) for i in range(3))
        n = np.cross(b - a, c - a)
        assert np.linalg.norm(n) > 1e-6, "degenerate face"
        if np.dot(n, outward) < 0:
            pts = list(reversed(pts))
        self.faces.append(tuple(self._v(p) for p in pts))

    def box(self, x0, y0, z0, x1, y1, z1):
        P = lambda x, y, z: (x, y, z)
        self.face([P(x0, y0, z0), P(x0, y1, z0), P(x0, y1, z1), P(x0, y0, z1)], (-1, 0, 0))
        self.face([P(x1, y0, z0), P(x1, y1, z0), P(x1, y1, z1), P(x1, y0, z1)], (1, 0, 0))
        self.face([P(x0, y0, z0), P(x1, y0, z0), P(x1, y0, z1), P(x0, y0, z1)], (0, -1, 0))
        self.face([P(x0, y1, z0), P(x1, y1, z0), P(x1, y1, z1), P(x0, y1, z1)], (0, 1, 0))
        self.face([P(x0, y0, z0), P(x1, y0, z0), P(x1, y1, z0), P(x0, y1, z0)], (0, 0, -1))
        self.face([P(x0, y0, z1), P(x1, y0, z1), P(x1, y1, z1), P(x0, y1, z1)], (0, 0, 1))

    def tri_count(self):
        return sum(1 if len(f) == 3 else 2 for f in self.faces)


def extrude_columns(b, columns, y0, y1):
    """Solid extruded along Y from XZ columns [(xa, xb, z_at_xa, z_at_xb)] standing on z = 0 (steps or a wedge)."""
    prev_top = 0.0
    for xa, xb, za, zb in columns:
        for y, out in ((y0, (0, -1, 0)), (y1, (0, 1, 0))):
            pts = [(xa, y, 0), (xb, y, 0), (xb, y, zb), (xa, y, za)]
            if za == 0:  # wedge tip column: triangle
                pts = [(xa, y, 0), (xb, y, 0), (xb, y, zb)]
            b.face(pts, out)
        b.face([(xa, y0, 0), (xb, y0, 0), (xb, y1, 0), (xa, y1, 0)], (0, 0, -1))
        tn = (0, 0, 1) if za == zb else (-(zb - za), 0, (xb - xa))
        b.face([(xa, y0, za), (xb, y0, zb), (xb, y1, zb), (xa, y1, za)], tn)
        if za > prev_top:  # riser facing -X where the previous column is lower
            b.face([(xa, y0, prev_top), (xa, y1, prev_top), (xa, y1, za), (xa, y0, za)], (-1, 0, 0))
        prev_top = zb
    xe, ze = columns[-1][1], columns[-1][3]
    b.face([(xe, y0, 0), (xe, y1, 0), (xe, y1, ze), (xe, y0, ze)], (1, 0, 0))


def octagon(cx, cy, r, rot=math.pi / 8):
    return [(cx + r * math.cos(rot + i * math.pi / 4), cy + r * math.sin(rot + i * math.pi / 4)) for i in range(8)]


