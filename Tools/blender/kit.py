def p_pad_ring(b):
    h = 5.0
    k = 1.0 / math.cos(math.pi / 8)  # circumradius so that the flats are 300 / 240 cm across
    outer, inner = octagon(150, 150, 150 * k), octagon(150, 150, 120 * k)
    for i in range(8):
        j = (i + 1) % 8
        o0, o1, i0, i1 = outer[i], outer[j], inner[i], inner[j]
        mid = ((o0[0] + o1[0]) / 2 - 150, (o0[1] + o1[1]) / 2 - 150)
        b.face([(o0[0], o0[1], h), (o1[0], o1[1], h), (i1[0], i1[1], h), (i0[0], i0[1], h)], (0, 0, 1))
        b.face([(o0[0], o0[1], 0), (o1[0], o1[1], 0), (o1[0], o1[1], h), (o0[0], o0[1], h)], (mid[0], mid[1], 0))
        b.face([(i0[0], i0[1], 0), (i1[0], i1[1], 0), (i1[0], i1[1], h), (i0[0], i0[1], h)], (-mid[0], -mid[1], 0))


